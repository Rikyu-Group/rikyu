/* 言語別の組版補正 — 韓国語は語中分割を禁止、タイ語は辞書改行に任せる */
const EXTRA_STYLE = {
  ko: '<style>body{word-break:keep-all}h1,h2,h3,.lead,.quote{overflow-wrap:break-word}</style>',
  th: '<style>h1,h2,h3,.lead,.quote{overflow-wrap:normal;line-break:auto}</style>',
};

/* ---------------- 生成 ---------------- */
let fail = 0;
for (const [lang, pairs] of Object.entries(L)) {
  let html = src;
  for (const [from, to] of pairs) {
    if (!html.includes(from)) {
      console.error(`✗ [${lang}] キーが見つかりません: ${from.slice(0, 60)}…`);
      fail++;
      continue;
    }
    html = html.split(from).join(to);
  }
  if (EXTRA_STYLE[lang]) html = html.replace('</head>', `${EXTRA_STYLE[lang]}\n</head>`);
  mkdirSync(resolve(root, `dist/${lang}`), { recursive: true });
  writeFileSync(resolve(root, `dist/${lang}/index.html`), html);
  const kb = (Buffer.byteLength(html, 'utf8') / 1024).toFixed(1);
  console.log(`✓ dist/${lang}/index.html（${kb}KB）`);
}
if (fail) {
  console.error(`\n✗ 置換漏れ ${fail} 件。dist/index.html との同期を確認してください。`);
  process.exit(1);
}
console.log('\n全言語の生成が完了しました。');
